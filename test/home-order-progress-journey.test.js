import test from 'node:test'
import assert from 'node:assert/strict'
import { journeyModel, journeyValue } from '../src/journey.js'
import { ErrorCode } from '../src/error-codes.js'
import { grantRewards, parseRewards } from '../src/rewards.js'
import { homeOrderFixture } from './home-order-progress-fixture.js'
const goals = (f) => journeyModel(f.tables).targets.filter((r) => r.tokens[0] === 15003)

test('all four15003 journey targets compile and actualCSFinishOrder source revision immediately synchronizes their true values', () => {
    const f = homeOrderFixture('order-journey-source')
    try {
        const model = journeyModel(f.tables),
            rows = goals(f)
        assert.equal(rows.length, 4)
        assert(rows.every((r) => r.supported && model.owner.has(r.id)))
        assert.equal(model.targets.filter((r) => r.supported).length, 175)
        assert.equal(model.referencedTargets.filter((r) => r.supported).length, 159)
        assert(rows.every((r) => journeyValue(f.tables, f.state(), r) === 0))
        const first = f.board().slots[0],
            packets = f.submit(first)
        assert(
            packets.some((p) => p.id === 11880),
            'CSProtoCSFinishOrder must wake journey observation without a Home/Exchange name match',
        )
        assert.equal(f.state().journey.targets[1320207].value, 1)
        f.complete(5)
        for (const row of rows) {
            assert.equal(journeyValue(f.tables, f.state(), row), row.targetParam)
            assert.equal(f.state().journey.targets[row.id].complete, true)
        }
        assert.equal(f.state().homeExchange.completedOrders, 6)
    } finally {
        f.close()
    }
})

test('journey synchronization failure rolls back the real order source and all rewards before a single successful retry', () => {
    const f = homeOrderFixture('order-journey-atomic')
    try {
        const slot = f.board().slots.find((r) => r.level === 2),
            row = f.tables.get('home_exchange_order').find((r) => r.orderID === slot.order_id)
        f.edit((s) => grantRewards(f.tables, s, parseRewards(row.orderNeedMaterials)))
        const before = f.state(),
            encode = f.protocol.encode
        let injected = false
        f.protocol.encode = function (name, data) {
            if (name === f.protocol.byId.get(11880).rsp) {
                injected = true
                throw Error('order-journey-sync')
            }
            return encode.call(this, name, data)
        }
        assert.throws(() => f.call('CSFinishOrder', { order_guid: slot.guid }), /order-journey-sync/)
        assert(injected)
        assert.deepEqual(f.state(), before)
        f.protocol.encode = encode
        f.call('CSFinishOrder', { order_guid: slot.guid })
        assert.equal(f.state().journey.targets[2030502].complete, true)
        assert.equal(f.state().homeExchange.completedOrders, 1)
    } finally {
        f.close()
    }
})

test('real completed tier goals preserve existing journey locks, and an isolated prerequisite fixture validates9869 reward rollback and idempotency', () => {
    const f = homeOrderFixture('order-journey-reward')
    try {
        f.complete(6)
        const beforeLock = f.state()
        assert.throws(
            () => f.call('JourneyTaskFinish', { u32s: [30502] }),
            (e) => e.code === ErrorCode.JourneyTypeLock,
        )
        assert.deepEqual(f.state(), beforeLock)
        // Only an unrelated existing tab prerequisite is supplied here. All four15003
        // target receipts and their order facts were generated by actual6227 above.
        // This does not claim a real gameplay completion of that earlier journey stage.
        f.edit((s) => {
            s.journey.tasks[20000] = { claimed: true, complete: true }
        })
        const ready = f.state(),
            encode = f.protocol.encode
        f.protocol.encode = function (name, data) {
            if (name === f.protocol.byId.get(9869).rsp) throw Error('order-journey-reward')
            return encode.call(this, name, data)
        }
        assert.throws(() => f.call('JourneyTaskFinish', { u32s: [30502, 30503] }), /order-journey-reward/)
        assert.deepEqual(f.state(), ready)
        f.protocol.encode = encode
        f.call('JourneyTaskFinish', { u32s: [30502, 30503] })
        for (const id of [2030502, 2030503]) assert.equal(f.state().journey.targets[id].claimed, true)
        const once = f.state(),
            reply = f.call('JourneyTaskFinish', { u32s: [30502, 30503] }).find((p) => p.id === 9869)
        assert.deepEqual(f.protocol.decode('Rewards', reply.payload).rewards, [])
        assert.deepEqual(f.state().player, once.player)
        assert.deepEqual(f.state().homeExchange, once.homeExchange)
    } finally {
        f.close()
    }
})
